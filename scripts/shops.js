/** Детерминированный ГСЧ. */
export function rng(seed) { let s = seed >>> 0 || 1; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296); }

/** Состав лавки: для каждого раздела — часть ассортимента. Ночной рынок — случайный набор. */
export function stockFor(type, seed) {
  const r = rng(seed), t = SHOP_TYPES[type], out = [];
  for (const c of t.cats) {
    const cat = CATALOG[c];
    if (cat.groups) {
      const n = type === "night" ? 2 : 4 + Math.floor(r() * 4);
      const groups = [...cat.groups].sort(() => r() - 0.5).slice(0, n);
      for (const [g, prices] of groups) {
        const ps = prices.split(" ").map(x => x.replace("_", " "));
        cat.pieces.forEach((p, i) => out.push({ cat: c, n: `${T(p)} — ${g.split(" — ")[0]}`, tier: tierByRu(ps[i]), note: T(g.split(" — ")[1]) }));
      }
    } else {
      const keep = type === "night" ? 0.35 : 0.85;
      for (const it of cat.items) if (r() < keep) out.push({ cat: c, n: T(it.n), tier: it.t, note: T(it.note) });
    }
  }
  return out;
}
function tierByRu(ru) { return Object.entries(TIERS).find(([, v]) => (v._ru ?? v.ru).replace("ё", "е").toLowerCase() === String(ru).replace("ё", "е").toLowerCase())?.[0] ?? "everyday"; }

